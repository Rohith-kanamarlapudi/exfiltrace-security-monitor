log = logging.getLogger("exfiltrace.network.capture")

# Ports -> friendly protocol names for the frontend contract.
_PORT_PROTOCOL = {53: "DNS", 443: "HTTPS", 445: "SMB", 80: "HTTP"}

#: Traffic generated by the combined launcher or Vite dev server is excluded
#: from stored capture data so the Network page does not count its own polling.
SELF_TRAFFIC_PORTS = frozenset({5001, 5173})


@dataclass
class ParsedPacket:
    """Minimal packet view shared by all capture modes."""

    timestamp: datetime
    src_ip: str
    dst_ip: str
    length: int
    protocol: str = "TCP"
    src_port: Optional[int] = None
    dst_port: Optional[int] = None
    hostname: Optional[str] = None
    #: A/AAAA answers from a DNS response.  Used only to associate later
    #: metadata-only flows with the hostname that was queried.
    dns_answer_ips: tuple[str, ...] = ()


def _normalise_ip(value: Optional[str]) -> Optional[str]:
    """Return an IP without an IPv6 zone suffix, or ``None``."""
    if not value:
        return None
    return str(value).split("%", 1)[0]


def is_loopback_ip(value: Optional[str]) -> bool:
    """True for IPv4/IPv6 loopback addresses (including ``::1``)."""
    ip = _normalise_ip(value)
    if not ip:
        return False
    try:
        return ipaddress.ip_address(ip).is_loopback
    except ValueError:
        return False


def is_self_traffic(
    packet: ParsedPacket,
    local_ip: Optional[str] = None,
    ignored_ports: Optional[Iterable[int]] = SELF_TRAFFIC_PORTS,
) -> bool:
    """True if a packet is loopback or belongs to the local backend/Vite ports."""
    if is_loopback_ip(packet.src_ip) or is_loopback_ip(packet.dst_ip):
        return True

    local = _normalise_ip(local_ip)
    if not local:
        return False
    ports = {int(port) for port in (ignored_ports or ()) if port is not None}
    src = _normalise_ip(packet.src_ip)
    dst = _normalise_ip(packet.dst_ip)
    if (src == local or dst == local) and (
        packet.src_port in ports or packet.dst_port in ports
    ):
        return True
    return False


def discover_capture_interfaces(tshark_path: Optional[str] = None):
    """Return parsed ``tshark -D`` entries (index, device name, description)."""
    return platform_support.discover_interfaces(tshark_path)


def list_capture_interfaces(tshark_path: Optional[str] = None) -> list[str]:
    """Return the interface names reported by ``tshark -D``.

    The output is parsed rather than guessed so ``--interface`` can fail with a
    useful message before a capture thread is started.
    """
    return [entry.name for entry in discover_capture_interfaces(tshark_path)]


def resolve_capture_interface(interface: str, tshark_path: Optional[str] = None) -> str:
    """Accept a TShark index, device name or friendly name; return the device name."""
    return platform_support.resolve_interface(
        interface, discover_capture_interfaces(tshark_path), tshark_path=tshark_path
    )


def validate_capture_interface(interface: str, tshark_path: Optional[str] = None) -> str:
    """Raise a clear error when ``interface`` is not listed by TShark."""
    return resolve_capture_interface(interface, tshark_path)


def detect_capture_interface(tshark_path: Optional[str] = None) -> str:
    """Auto-detect a suitable non-loopback interface from ``tshark -D``."""
    return platform_support.detect_default_interface(
        discover_capture_interfaces(tshark_path), tshark_path=tshark_path
    )


def discover_local_ip(interface: Optional[str] = None) -> Optional[str]:
    """Find the local IPv4 address using only portable socket calls.

    The UDP ``connect`` does not send a packet; it asks the routing table which
    source address would be used.  This works on macOS and Windows without
    ``ifconfig``, ``ip``, psutil or extra privileges.  ``interface`` is accepted
    for API compatibility and logging; the operating system chooses the source
    address for the default route.
    """
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sock:
            sock.connect(("192.0.2.1", 9))
            return _normalise_ip(sock.getsockname()[0])
    except OSError:
        log.debug("socket local-IP lookup failed for interface %s", interface, exc_info=True)
        return None


def _protocol_for(transport: str, dst_port: Optional[int], src_port: Optional[int]) -> str:
    """Best-effort protocol name from transport + ports."""
    for port in (dst_port, src_port):
        if port in _PORT_PROTOCOL:
            return _PORT_PROTOCOL[port]
    return transport


def direction_for(src_ip: str, dst_ip: str, local_ip: Optional[str] = None) -> str:
    """OUTBOUND | INBOUND | INTERNAL.

    When ``local_ip`` is supplied (live capture), direction is based on which
    side is this Mac.  The private-range heuristic is retained as a fallback for
    simulation and callers that do not know their local address.
    """
    if local_ip:
        local = _normalise_ip(local_ip)
        src = _normalise_ip(src_ip)
        dst = _normalise_ip(dst_ip)
        if src == local and dst == local:
            return "INTERNAL"
        if src == local:
            return "OUTBOUND"
        if dst == local:
            return "INBOUND"
        return "INTERNAL"

    src_priv, dst_priv = is_private(src_ip), is_private(dst_ip)
    if src_priv and dst_priv:
        return "INTERNAL"
    if src_priv and not dst_priv:
        return "OUTBOUND"
    if dst_priv and not src_priv:
        return "INBOUND"
    return "OUTBOUND"


def _merge_flow(flows: dict, packet: ParsedPacket, direction: str) -> None:
    """Fold a packet into the aggregated flow keyed by (src,dst,dport,proto)."""
    key = (packet.src_ip, packet.dst_ip, packet.dst_port, packet.protocol)
    flow = flows.get(key)
    ts = to_iso_utc(packet.timestamp)
    if flow is None:
        flow = Flow(
            src_ip=packet.src_ip,
            dst_ip=packet.dst_ip,
            dst_port=packet.dst_port,
            src_port=packet.src_port,
            protocol=packet.protocol,
            first_seen=ts,
            last_seen=ts,
            hostname=packet.hostname,
        )
        flows[key] = flow
    if direction == "INBOUND":
        flow.bytes_in += packet.length
    else:
        flow.bytes_out += packet.length
    flow.packets += 1
    flow.last_seen = ts
    if packet.hostname and not flow.hostname:
        flow.hostname = packet.hostname


class SimulatedTrafficSource:
    """Deterministic-ish synthetic traffic so demos work without TShark/root."""

    def __init__(self, local_ip: str = config.SIM_LOCAL_IP, seed: Optional[int] = 1337) -> None:
        self.local_ip = local_ip
        self._rng = random.Random(seed)

    def generate(self, interval_index: int, now: datetime) -> list[ParsedPacket]:
        """Return the packets for one interval."""
        rng = self._rng
        local = self.local_ip
        packets: list[ParsedPacket] = []

        def add(src, dst, dport, proto, length, sport=None, host=None):
            packets.append(ParsedPacket(now, src, dst, length, proto, sport, dport, host))

        # Routine background traffic.
        add(local, "192.168.1.1", 53, "DNS", rng.randint(70, 120), rng.randint(30000, 60000))
        add(local, "192.168.1.10", 445, "SMB", rng.randint(120_000, 400_000), rng.randint(30000, 60000), "fileserver.corp.local")
        add(local, "142.250.183.14", 443, "HTTPS", rng.randint(10_000, 40_000), rng.randint(30000, 60000), "www.google.com")
        add(local, "13.107.42.14", 443, "HTTPS", rng.randint(30_000, 80_000), rng.randint(30000, 60000), "outlook.office365.com")
        add("104.18.32.47", local, 443, "HTTPS", rng.randint(20_000, 60_000), 443, "cdn.updates.vendor.com")

        # Occasional large upload to a personal cloud host (medium risk).
        if interval_index > 0 and interval_index % 20 == 0:
            add(local, "198.51.100.77", 443, "HTTPS", 8 * 1024 * 1024, rng.randint(30000, 60000), "dl.personal-cloud-drive.io")

        return packets


class CaptureEngine:
    """Owns the capture thread, flow table, detector state and DB writes."""

    def __init__(
        self,
        *,
        db_path: Optional[str] = None,
        interface: Optional[str] = None,
        mode: str = "simulate",
        pcap_file: Optional[str] = None,
        session_label: Optional[str] = None,
        usb_session_id: Optional[str] = None,
        interval_seconds: Optional[float] = None,
        local_ip: Optional[str] = None,
        promiscuous: bool = False,
        ignored_ports: Optional[Iterable[int]] = None,
        tshark_path: Optional[str] = None,
    ) -> None:
        self.db_path = db_path
        self.interface = interface or config.CAPTURE_INTERFACE
        self.tshark_path = tshark_path
        self.mode = mode
        self.pcap_file = pcap_file
        self.session_label = session_label
        self.usb_session_id = usb_session_id
        self.interval_seconds = float(interval_seconds or config.STATS_INTERVAL_SECONDS)
        self.local_ip = local_ip if local_ip is not None else (
            config.SIM_LOCAL_IP if mode == "simulate" else None
        )
        self.promiscuous = bool(promiscuous)
        self.ignored_ports = frozenset(
            int(port) for port in (SELF_TRAFFIC_PORTS if ignored_ports is None else ignored_ports)
            if port is not None
        )

        self.baseline = OutboundBaseline()
        self.tracker = FirstSeenTracker()
        self.dns_map: dict[str, str] = {}

        self._flows: dict = {}
        self._lock = threading.RLock()
        self._stop = threading.Event()
        self._thread: Optional[threading.Thread] = None
        self._worker: Optional[threading.Thread] = None
        self._capture: Optional[object] = None
        self._packet_queue: "queue.Queue[ParsedPacket]" = queue.Queue(maxsize=100_000)
        self._conn: Optional[object] = None
        self._session_id: Optional[int] = None

        self._status = {
            "running": False,
            "mode": mode,
            "interface": self.interface,
            "started_at": None,
            "last_flush": None,
            "packets": 0,
            "flows": 0,
            "events": 0,
            "alerts": 0,
            "session_label": session_label,
            "usb_session_id": usb_session_id,
            "local_ip": self.local_ip,
            "promiscuous": self.promiscuous,
            "tshark_path": self.tshark_path,
            "last_error": None,
        }

    # -- lifecycle -----------------------------------------------------------
    def open(self) -> "CaptureEngine":
        """Open the DB connection and a capture-session row without starting a thread."""
        if self._conn is None:
            self._conn = db.get_connection(self.db_path)
            db.init_db(self._conn)
        if self._session_id is None:
            self._session_id = db.insert_capture_session(
                self._conn,
                started_at=iso_now(),
                trigger=self.session_label or self.mode,
                usb_session_id=self.usb_session_id,
            )
        return self

    def close_session(self) -> None:
        """Stamp the capture session's ``ended_at`` (safe to call twice)."""
        if self._conn is not None and self._session_id is not None:
            db.close_capture_session(self._conn, self._session_id, iso_now())
            self._session_id = None

    def start(self) -> dict:
        """Validate prerequisites, open a capture session and start the thread."""
        if self._status["running"]:
            return self.status()
        self._validate_mode()
        self.open()
        self._stop.clear()
        self._status.update(running=True, started_at=iso_now(), last_error=None)
        self._thread = threading.Thread(target=self._run_loop, name="exfiltrace-capture", daemon=True)
        self._thread.start()
        log.info("capture started (mode=%s, interface=%s)", self.mode, self.interface)
        return self.status()

    def stop(self, timeout: float = 5.0) -> dict:
        """Signal the thread to stop, flush remaining flows and close the session."""
        if not self._status["running"] and self._conn is None:
            return self.status()
        self._stop.set()
        # PyShark owns an asyncio loop in the capture thread.  Closing the
        # capture from this thread would race that loop; the worker's finally
        # block performs close() once sniff_continuously() yields control.
        for thread in (self._thread, self._worker):
            if thread and thread.is_alive():
                thread.join(timeout=timeout)
        if self._conn is not None:
            try:
                self.flush_interval()
            except Exception as exc:  # pragma: no cover - defensive
                self._status["last_error"] = str(exc)
                log.exception("error flushing on stop")
            self.close_session()
        self._status["running"] = False
        self._capture = None
        log.info("capture stopped")
        return self.status()

    def status(self) -> dict:
        """Snapshot of engine state for /status style introspection."""
        with self._lock:
            snapshot = dict(self._status)
            snapshot["flows"] = len(self._flows)
        return snapshot

    # -- validation ----------------------------------------------------------
    def _validate_mode(self) -> None:
        if self.mode == "live":
            try:
                import pyshark  # noqa: F401
            except Exception as exc:  # pragma: no cover - env dependent
                raise RuntimeError(
                    "Live capture needs the 'pyshark' package. Install it with "
                    "'pip install pyshark' and make sure TShark is installed."
                ) from exc
            self.tshark_path = platform_support.find_tshark(self.tshark_path)
            if self.interface:
                self.interface = resolve_capture_interface(
                    self.interface, tshark_path=self.tshark_path
                )
            else:
                self.interface = detect_capture_interface(tshark_path=self.tshark_path)
            self._status["interface"] = self.interface
            self._status["tshark_path"] = self.tshark_path
        elif self.mode == "pcap":
            if not self.pcap_file:
                raise RuntimeError("PCAP replay requires a pcap_file path.")
        elif self.mode != "simulate":
            raise RuntimeError(f"Unknown capture mode: {self.mode!r}")

    # -- ingestion -----------------------------------------------------------
    def ingest_packet(self, packet: ParsedPacket) -> None:
        """Add one packet to the current flow table (thread-safe)."""
        direction = direction_for(packet.src_ip, packet.dst_ip, self.local_ip)
        with self._lock:
            _merge_flow(self._flows, packet, direction)
            if packet.hostname and packet.dns_answer_ips:
                for answer_ip in packet.dns_answer_ips:
                    if is_public(answer_ip):
                        self.dns_map[answer_ip] = packet.hostname
            elif packet.hostname and packet.protocol != "DNS" and is_public(packet.dst_ip):
                self.dns_map[packet.dst_ip] = packet.hostname

    def ingest_flow(self, flow: Flow) -> None:
        """Directly merge an already-aggregated flow (used by tests/demos)."""
        if not flow.packets and (flow.bytes_out + flow.bytes_in) > 0:
            # Callers that inject pre-aggregated bytes may omit the packet count.
            flow.packets = max(1, int((flow.bytes_out + flow.bytes_in) // 1400))
        # NB: leave first_seen/last_seen as-is when unset; flush_interval stamps
        # them with the interval timestamp so injected flows land in the right bucket.
        with self._lock:
            key = (flow.src_ip, flow.dst_ip, flow.dst_port, flow.protocol)
            existing = self._flows.get(key)
            if existing is None:
                self._flows[key] = flow
            else:
                existing.bytes_out += flow.bytes_out
                existing.bytes_in += flow.bytes_in
                existing.packets += flow.packets
                existing.last_seen = flow.last_seen or existing.last_seen
                existing.first_seen = existing.first_seen or flow.first_seen
                if flow.hostname and not existing.hostname:
                    existing.hostname = flow.hostname

    def flush_interval(self, timestamp: Optional[str] = None) -> dict:
        """Aggregate current flows, persist everything, run detection.

        Returns a small summary (interval, events, alerts) and resets the flow table.
        """
        assert self._conn is not None, "engine not started"
        ts = timestamp or iso_now()
        with self._lock:
            flows = list(self._flows.values())
            self._flows = {}

        if not flows:
            # Keep the baseline ticking even across quiet intervals.
            stats = IntervalStats(timestamp=ts, bytes_out=0, bytes_in=0, packets=0, active_connections=0)
            alerts = detect_interval(stats, [], self.baseline, self.tracker)
            db.insert_traffic_stat(
                self._conn,
                timestamp=ts,
                bytes_out=0,
                bytes_in=0,
                suspicious_bytes=0,
                packets=0,
                active_connections=0,
            )
            self._status["last_flush"] = ts
            return {"interval": ts, "events": 0, "alerts": len(alerts)}

        bytes_out = sum(f.bytes_out for f in flows)
        bytes_in = sum(f.bytes_in for f in flows)
        packets = sum(f.packets for f in flows)
        stats = IntervalStats(
            timestamp=ts,
            bytes_out=bytes_out,
            bytes_in=bytes_in,
            packets=packets,
            active_connections=len(flows),
        )

        alerts = detect_interval(stats, flows, self.baseline, self.tracker)

        high_dsts = {a.dst_ip for a in alerts if a.severity == "high" and a.dst_ip}
        flagged_dsts = {a.dst_ip for a in alerts if a.severity in ("medium", "high") and a.dst_ip}
        suspicious_bytes = sum(f.bytes_out for f in flows if f.dst_ip in flagged_dsts)

        # Persist raw flows.
        for f in flows:
            db.insert_connection(
                self._conn,
                src_ip=f.src_ip,
                src_port=f.src_port,
                dst_ip=f.dst_ip,
                dst_port=f.dst_port,
                protocol=f.protocol,
                bytes_out=f.bytes_out,
                bytes_in=f.bytes_in,
                packets=f.packets,
                first_seen=f.first_seen or ts,
                last_seen=f.last_seen or ts,
            )

        # Persist interval aggregate.
        db.insert_traffic_stat(
            self._conn,
            timestamp=ts,
            bytes_out=bytes_out,
            bytes_in=bytes_in,
            suspicious_bytes=suspicious_bytes,
            packets=packets,
            active_connections=len(flows),
        )

        # Persist notable flows as network_events.
        events_written = 0
        for f in flows:
            if f.bytes_out + f.bytes_in < config.MIN_EVENT_BYTES:
                continue
            direction = direction_for(f.src_ip, f.dst_ip, self.local_ip)
            host = f.hostname or self.dns_map.get(f.dst_ip) or f.dst_ip
            db.insert_event(
                self._conn,
                timestamp=f.last_seen or ts,
                source_ip=f.src_ip,
                destination_ip=f.dst_ip,
                destination_host=host,
                protocol=f.protocol,
                port=f.dst_port,
                packet_size_bytes=f.bytes_out + f.bytes_in,
                direction=direction,
                risk=classify_flow_risk(f, high_dsts),
                usb_session=self.usb_session_id,
            )
            events_written += 1

        # Persist alerts.
        for a in alerts:
            db.insert_alert(
                self._conn,
                timestamp=a.timestamp,
                dst_ip=a.dst_ip,
                dst_port=a.dst_port,
                reason=a.reason,
                severity=a.severity,
                bytes=a.bytes,
                zscore=a.zscore,
            )

        with self._lock:
            self._status["last_flush"] = ts
            self._status["events"] += events_written
            self._status["alerts"] += len(alerts)

        return {"interval": ts, "events": events_written, "alerts": len(alerts)}

    # -- run loops -----------------------------------------------------------
    def _run_loop(self) -> None:
        try:
            if self.mode == "live":
                self._run_live()
            elif self.mode == "pcap":
                self._run_pcap()
            else:
                self._run_simulation()
        except Exception as exc:  # pragma: no cover - env dependent
            log.exception("capture loop crashed")
            self._status["last_error"] = str(exc)
            self._status["running"] = False

    def _run_simulation(self) -> None:
        source = SimulatedTrafficSource(local_ip=self.local_ip)
        index = 0
        next_flush = utcnow()
        while not self._stop.is_set():
            now = utcnow()
            for packet in source.generate(index, now):
                self.ingest_packet(packet)
                self._status["packets"] += 1
            index += 1
            now = utcnow()
            if now >= next_flush:
                self.flush_interval(to_iso_utc(now))
                next_flush = datetime.fromtimestamp(now.timestamp() + self.interval_seconds, tz=timezone.utc)
            self._stop.wait(config.SIM_INTERVAL_SECONDS)

    def _run_live(self) -> None:
        self._start_pyshark_worker()

        next_flush = utcnow().timestamp() + self.interval_seconds
        while not self._stop.is_set():
            drained = False
            try:
                while True:
                    packet = self._packet_queue.get_nowait()
                    self.ingest_packet(packet)
                    self._status["packets"] += 1
                    drained = True
            except queue.Empty:
                pass
            if utcnow().timestamp() >= next_flush:
                self.flush_interval()
                next_flush = utcnow().timestamp() + self.interval_seconds
            self._stop.wait(0.2 if drained else 0.5)

    def _start_pyshark_worker(self) -> None:
        """Start PyShark in its own thread with its own event loop.

        PyShark needs an asyncio loop in the thread that reads TShark output.
        The loop is created here (Proactor on Windows) rather than borrowed
        from Flask's main thread, which also keeps Ctrl+C shutdown clean.
        """
        interface = self.interface
        tshark_path = self.tshark_path
        promiscuous = self.promiscuous

        def worker() -> None:
            import pyshark  # imported lazily; validated in _validate_mode

            loop = _create_capture_event_loop()
            capture = None
            try:
                options = {
                    "interface": interface,
                    "use_json": True,
                    "include_raw": False,
                    "eventloop": loop,
                }
                if tshark_path:
                    options["tshark_path"] = tshark_path
                if not promiscuous:
                    # TShark defaults to promiscuous mode; -p keeps the opt-in promise.
                    options["custom_parameters"] = ["-p"]
                capture = pyshark.LiveCapture(**options)
                self._capture = capture
                for packet in capture.sniff_continuously():
                    if self._stop.is_set():
                        break
                    parsed = self._parse_pyshark_packet(packet)
                    if parsed is not None and not is_self_traffic(
                        parsed, self.local_ip, self.ignored_ports
                    ):
                        try:
                            self._packet_queue.put(parsed, timeout=1)
                        except queue.Full:  # pragma: no cover
                            log.warning("packet queue full; dropping packet")
            except Exception as exc:  # pragma: no cover - env dependent
                if not self._stop.is_set():
                    message = platform_support.explain_capture_error(exc)
                    self._status["last_error"] = message
                    log.error("%s", message)
                    log.debug("live capture worker error", exc_info=True)
            finally:
                if capture is not None:
                    try:
                        capture.close()
                    except Exception:  # pragma: no cover - PyShark cleanup is defensive
                        log.debug("error closing PyShark capture", exc_info=True)
                _close_capture_event_loop(loop)

        self._worker = threading.Thread(target=worker, name="exfiltrace-pyshark", daemon=True)
        self._worker.start()

    def _run_pcap(self) -> None:
        import pyshark

        capture = pyshark.FileCapture(self.pcap_file, keep_packets=False)
        window_start: Optional[float] = None
        for packet in capture:
            if self._stop.is_set():
                break
            parsed = self._parse_pyshark_packet(packet)
            if parsed is None:
                continue
            ts = parsed.timestamp.timestamp()
            if window_start is None:
                window_start = ts
            if ts - window_start >= self.interval_seconds:
                self.flush_interval(to_iso_utc(parsed.timestamp))
                window_start = ts
            self.ingest_packet(parsed)
            self._status["packets"] += 1
        capture.close()
        self.flush_interval()

    @staticmethod
    def _parse_pyshark_packet(packet) -> Optional[ParsedPacket]:
        """Convert a PyShark packet into a ParsedPacket (best effort)."""
        try:
            ts = float(packet.sniff_timestamp)
            when = datetime.fromtimestamp(ts, tz=timezone.utc)
        except Exception:
            when = utcnow()

        src_ip = dst_ip = None
        for layer in ("ip", "ipv6"):
            if hasattr(packet, layer):
                lyr = getattr(packet, layer)
                src_ip = getattr(lyr, "src", None)
                dst_ip = getattr(lyr, "dst", None)
                if src_ip and dst_ip:
                    break
        if not src_ip or not dst_ip:
            return None

        transport = "TCP"
        src_port = dst_port = None
        if hasattr(packet, "tcp"):
            transport, src_port, dst_port = "TCP", _int(getattr(packet.tcp, "srcport", None)), _int(getattr(packet.tcp, "dstport", None))
        elif hasattr(packet, "udp"):
            transport, src_port, dst_port = "UDP", _int(getattr(packet.udp, "srcport", None)), _int(getattr(packet.udp, "dstport", None))

        hostname = None
        dns_answer_ips: tuple[str, ...] = ()
        if hasattr(packet, "dns"):
            hostname = _layer_text(packet.dns, "qry.name", "qry_name", "name")
            dns_answer_ips = _layer_values(packet.dns, "a", "aaaa")
        elif hasattr(packet, "tls"):
            # PyShark 0.6 keeps the dotted tshark field name
            # (tls.handshake.extensions_server_name); older versions expose
            # the underscore variant.  Support both without storing payloads.
            hostname = _layer_text(
                packet.tls,
                "handshake.extensions_server_name",
                "handshake_extensions_server_name",
                "extensions_server_name",
            )

        protocol = _protocol_for(transport, dst_port, src_port)
        length = _int(getattr(packet, "length", None)) or 0
        return ParsedPacket(
            when,
            src_ip,
            dst_ip,
            length,
            protocol,
            src_port,
            dst_port,
            hostname,
            dns_answer_ips,
        )


def _layer_text(layer, *names) -> Optional[str]:
    """Read the first present metadata field from a PyShark layer."""
    values = _layer_values(layer, *names)
    return values[0] if values else None


def _text_value(value) -> Optional[str]:
    """Normalise a PyShark string/list field to a short metadata string."""
    if isinstance(value, (list, tuple)):
        value = value[0] if value else None
    if value is None:
        return None
    text = str(value).strip()
    return text or None


def _layer_values(layer, *names) -> tuple[str, ...]:
    """Read metadata values from a PyShark layer.

    TShark's JSON output nests DNS answers under ``Answers`` and may expose TLS
    handshake fields through intermediate objects.  Walk the layer's raw field
    map by field name so those values are found without ever touching packet
    bytes.  Simple namespace mocks used by tests take the ``get_field`` path.
    """
    values: list[str] = []
    fields = getattr(layer, "_all_fields", None)
    if isinstance(fields, dict):
        _collect_field_values(fields, names, values)
        if values:
            return tuple(values)

    for name in names:
        value = None
        get_field = getattr(layer, "get_field", None)
        if callable(get_field):
            try:
                value = get_field(name)
            except (AttributeError, KeyError, TypeError):
                value = None
        if value is None:
            value = getattr(layer, name, None)
        if value is None:
            continue

        _append_metadata_values(value, values)
        if values:
            return tuple(values)
    return ()


def _collect_field_values(fields, names: tuple[str, ...], values: list[str]) -> None:
    """Recursively collect values whose TShark field name ends with ``names``."""
    if isinstance(fields, dict):
        for key, value in fields.items():
            if isinstance(key, str) and any(
                key == name or key.endswith(f".{name}") for name in names
            ):
                _append_metadata_values(value, values)
            elif isinstance(value, (dict, list, tuple)):
                _collect_field_values(value, names, values)
    elif isinstance(fields, (list, tuple)):
        for item in fields:
            _collect_field_values(item, names, values)


def _append_metadata_values(value, values: list[str]) -> None:
    """Flatten PyShark field containers/duplicate fields into unique strings."""
    if isinstance(value, dict):
        for key in ("raw_value", "value"):
            if key in value:
                _append_metadata_values(value[key], values)
                return
        return
    candidates = getattr(value, "all_fields", None)
    if candidates is None:
        candidates = value if isinstance(value, (list, tuple)) else [value]
    for candidate in candidates:
        text = _text_value(getattr(candidate, "raw_value", candidate))
        if text and text not in values:
            values.append(text)


def _int(value) -> Optional[int]:
    try:
        return int(value)
    except (TypeError, ValueError):
        return None


def _create_capture_event_loop() -> asyncio.AbstractEventLoop:
    """Create an event loop usable by PyShark in the capture thread."""
    if sys.platform == "win32":
        # PyShark spawns TShark with asyncio subprocesses, which need the
        # Proactor loop on Windows.  getattr keeps macOS/Linux imports safe.
        policy_class = getattr(asyncio, "WindowsProactorEventLoopPolicy", None)
        if policy_class is not None:
            try:
                asyncio.set_event_loop_policy(policy_class())
            except Exception:  # pragma: no cover - defensive
                log.debug("could not install Proactor event loop policy", exc_info=True)
    loop = asyncio.new_event_loop()
    asyncio.set_event_loop(loop)
    return loop


def _close_capture_event_loop(loop: asyncio.AbstractEventLoop) -> None:
    """Close and detach the capture thread's event loop."""
    try:
        if not loop.is_closed():
            loop.close()
    except Exception:  # pragma: no cover - defensive
        log.debug("error closing capture event loop", exc_info=True)
    try:
        asyncio.set_event_loop(None)
    except Exception:  # pragma: no cover - defensive
        pass


